-- ============================================================
-- S4: 초대코드 만료·재발급·시도 제한
--
-- 문제
--   - 초대코드가 영구히 유효해 한 번 유출되면 막을 방법이 없었다.
--   - 재발급 기능이 없었다.
--   - 참여 시도 횟수 제한이 없어 무작위 대입이 가능했다.
--   - 방장이 REST로 invite_code를 'A' 같은 약한 값으로 바꿀 수 있었다.
--   - 코드 생성에 random()(암호학적 난수가 아님)을 썼다.
--
-- 수정
--   1) invite_code_expires_at 추가 (기본 7일). 기존 공간도 지금부터 7일 뒤 만료.
--   2) 새 코드는 8자리, gen_random_bytes 기반으로 생성.
--   3) regenerate_invite_code(p_group_id): 방장만, 이전 코드 즉시 무효.
--   4) join_group_by_invite_code: 사용자당 15분 내 실패 10회면 차단.
--      틀리거나 만료된 코드는 예외 대신 NULL을 돌려준다
--      (예외를 던지면 실패 기록까지 롤백되기 때문).
--      이미 멤버면 만료 여부와 관계없이 그 공간 id를 돌려준다.
--   5) groups UPDATE 권한을 name 컬럼으로 제한.
-- ============================================================

-- ------------------------------------------------------------
-- 1) 만료 컬럼
-- ------------------------------------------------------------

ALTER TABLE public.groups
  ADD COLUMN IF NOT EXISTS invite_code_expires_at timestamptz;

UPDATE public.groups
SET invite_code_expires_at = now() + interval '7 days'
WHERE invite_code_expires_at IS NULL;

ALTER TABLE public.groups
  ALTER COLUMN invite_code_expires_at SET DEFAULT (now() + interval '7 days'),
  ALTER COLUMN invite_code_expires_at SET NOT NULL;

-- ------------------------------------------------------------
-- 5) groups는 name만 직접 수정 가능
--    (invite_code, invite_code_expires_at, owner_id는 RPC로만 변경)
-- ------------------------------------------------------------

REVOKE UPDATE ON TABLE public.groups FROM anon, authenticated;
GRANT UPDATE (name) ON TABLE public.groups TO authenticated;

-- ------------------------------------------------------------
-- 시도 기록
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.invite_join_attempts (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      uuid        NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  attempted_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS invite_join_attempts_user_time_idx
  ON public.invite_join_attempts (user_id, attempted_at DESC);

-- 정책 없음: SECURITY DEFINER 함수만 읽고 쓴다.
ALTER TABLE public.invite_join_attempts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.invite_join_attempts FROM anon, authenticated;

-- ------------------------------------------------------------
-- 2) 코드 생성 (내부 전용)
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.generate_invite_code()
  RETURNS text
  LANGUAGE plpgsql
  VOLATILE
  SET search_path TO ''
  AS $function$
declare
    -- 32자. 256 % 32 = 0이라 바이트 → 문자 변환에 편향이 없다.
    characters constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
    random_bytes bytea;
    candidate text;
    attempt integer := 0;
begin
    loop
        attempt := attempt + 1;
        random_bytes := extensions.gen_random_bytes(8);
        candidate := '';

        for i in 0..7 loop
            candidate := candidate || substr(
                characters,
                (get_byte(random_bytes, i) % 32) + 1,
                1
            );
        end loop;

        exit when not exists (
            select 1 from public.groups where invite_code = candidate
        );

        if attempt >= 10 then
            raise exception '초대코드를 생성하지 못했습니다. 다시 시도해주세요.';
        end if;
    end loop;

    return candidate;
end;
$function$;

REVOKE ALL ON FUNCTION public.generate_invite_code() FROM PUBLIC, anon, authenticated;

-- ------------------------------------------------------------
-- create_group: 새 코드 생성 방식 사용 (만료일은 컬럼 기본값)
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.create_group (
  group_name text
)
  RETURNS bigint
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
declare
    new_group_id bigint;
begin
    if auth.uid() is null then
        raise exception '로그인이 필요합니다.';
    end if;

    group_name := trim(group_name);

    if group_name is null
       or char_length(group_name) < 1
       or char_length(group_name) > 30 then
        raise exception '그룹 이름은 1~30자로 입력해주세요.';
    end if;

    insert into public.groups (name, invite_code, owner_id)
    values (group_name, public.generate_invite_code(), auth.uid())
    returning id into new_group_id;

    insert into public.group_members (group_id, user_id)
    values (new_group_id, auth.uid());

    return new_group_id;
end;
$function$;

-- ------------------------------------------------------------
-- 3) 재발급
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.regenerate_invite_code (
  p_group_id bigint
)
  RETURNS text
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
declare
    new_code text;
begin
    if auth.uid() is null then
        raise exception '로그인이 필요합니다.';
    end if;

    if not exists (
        select 1 from public.groups
        where id = p_group_id and owner_id = auth.uid()
    ) then
        raise exception '방장만 초대코드를 다시 만들 수 있습니다.';
    end if;

    new_code := public.generate_invite_code();

    update public.groups
    set invite_code = new_code,
        invite_code_expires_at = now() + interval '7 days'
    where id = p_group_id;

    return new_code;
end;
$function$;

REVOKE ALL ON FUNCTION public.regenerate_invite_code(bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.regenerate_invite_code(bigint) TO authenticated;

-- ------------------------------------------------------------
-- 4) 참여 (만료 + 시도 제한)
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.join_group_by_invite_code (
  code text
)
  RETURNS bigint
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
declare
    v_user_id uuid := auth.uid();
    v_code text := upper(trim(coalesce(code, '')));
    v_group record;
    v_recent_failures integer;
begin
    if v_user_id is null then
        raise exception '로그인이 필요합니다.';
    end if;

    if v_code = '' then
        raise exception '초대코드를 입력해주세요.';
    end if;

    -- 오래된 기록 정리 (본인 것만)
    delete from public.invite_join_attempts
    where user_id = v_user_id
      and attempted_at < now() - interval '1 day';

    select count(*)
    into v_recent_failures
    from public.invite_join_attempts
    where user_id = v_user_id
      and attempted_at > now() - interval '15 minutes';

    if v_recent_failures >= 10 then
        raise exception '초대코드를 너무 많이 틀렸어요. 잠시 후 다시 시도해주세요.';
    end if;

    select id, invite_code_expires_at
    into v_group
    from public.groups
    where invite_code = v_code;

    if v_group.id is not null then
        -- 이미 멤버면 만료 여부와 관계없이 이동
        if exists (
            select 1 from public.group_members
            where group_id = v_group.id and user_id = v_user_id
        ) then
            return v_group.id;
        end if;

        if v_group.invite_code_expires_at > now() then
            insert into public.group_members (group_id, user_id)
            values (v_group.id, v_user_id)
            on conflict (group_id, user_id) do nothing;

            return v_group.id;
        end if;
    end if;

    -- 없는 코드 또는 만료된 코드: 실패 기록 후 NULL
    insert into public.invite_join_attempts (user_id)
    values (v_user_id);

    return null;
end;
$function$;

REVOKE ALL ON FUNCTION public.join_group_by_invite_code(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.join_group_by_invite_code(text) TO authenticated;
